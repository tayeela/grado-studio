// labelfmt.js: станции («ст. ж/д …») и кавычки в подписях листа (запуск — tests/test_labelfmt_js.py).
const assert = require("assert");
const F = require("../web/labelfmt.js");
let n = 0; const eq = (a, b, msg) => { assert.strictEqual(a, b, "FAIL: " + msg + " | " + JSON.stringify(a)); n++; };
const NB = " ", P = "ст." + NB + "ж/д" + NB;
eq(F.placeLabel({ "Землепользование": "railway" }, "Калошино"), P + "Калошино", "OSM landuse=railway с названием");
eq(F.placeLabel({ railway: "station" }, "Перово"), P + "Перово", "тег railway=station");
eq(F.placeLabel({ "Железная дорога": "yard" }, "Калошино"), P + "Калошино", "тег yard");
eq(F.placeLabel({ ft_type_name: "transport-railway-station" }, "Новогиреево"), P + "Новогиреево", "тип Яндекса");
eq(F.placeLabel({ "Землепользование": "railway" }, "ст. Калошино"), P + "Калошино", "«ст.» не удваивается");
eq(F.placeLabel({ "Землепользование": "railway" }, "ст. ж/д Калошино"), P + "Калошино", "уже с приставкой");
eq(F.placeLabel({ "Землепользование": "railway" }, "Станция Калошино"), P + "Калошино", "«Станция» → ст. ж/д");
eq(F.placeLabel({ "Землепользование": "railway" }, "Новая Деревня"), P + "Новая Деревня", "двусловное название");
eq(F.placeLabel({ "Землепользование": "railway" }, "Депо Перово"), "Депо Перово", "депо — не станция");
eq(F.placeLabel({ "Землепользование": "industrial" }, "Калошино"), "Калошино", "не станция — название как есть");
eq(F.placeLabel({ "Землепользование": "residential" }, "СНТ Ручеёк"), "СНТ Ручеёк", "СНТ");
eq(F.placeLabel({ "Землепользование": "railway" }, "Стахановская"), P + "Стахановская", "«Ст» в начале слова — не приставка");
eq(F.placeLabel({ get: k => k === "Землепользование" ? "railway" : null }, "Калошино"), P + "Калошино", "объект с get()");
eq(F.placeLabel({}, ""), null, "без названия");
eq(F.stationLabel("Станция"), "", "только слово «станция»");
eq(F.guillemets('ЖК "Сиреневый парк"'), "ЖК «Сиреневый парк»", "кавычки ЖК");
eq(F.guillemets('ГСК "Статор"'), "ГСК «Статор»", "кавычки ГСК");
eq(F.guillemets('"Ромашка" (СНТ)'), "«Ромашка» (СНТ)", "кавычки в начале");
eq(F.guillemets('ЖК “Сиреневый парк”'), "ЖК «Сиреневый парк»", "английские фигурные");
eq(F.guillemets('ГСК "Статор'), 'ГСК "Статор', "нечётное число — не трогаем");
eq(F.guillemets("ул. Придорожная"), "ул. Придорожная", "без кавычек");
eq(F.placeLabel({ "Землепользование": "railway" }, "Платформа Калошино"), "Платформа Калошино", "платформа — не станция, без приставки");
eq(F.placeLabel({ "Землепользование": "railway" }, "ТЭЦ-23"), "ТЭЦ-23", "ТЭЦ на ж/д землях — без приставки");
console.log(n + " checks ok");
