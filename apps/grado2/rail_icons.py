def icon_ops(iid, x, y, height):
    """Операции печати значка с центром в (x, y), высотой height мм: [{op: path, rings, fill, …}]."""
    (vx, vy, vw, vh), paths = ICONS[iid]
    k = height / vh
    x0, y0 = x - vw * k / 2, y - height / 2
    out = []
    for n, (d, col) in enumerate(paths):
        rings = [[(x0 + (px - vx) * k, y0 + (py - vy) * k) for px, py in r] for r in flatten(d)]
        c = tuple(int(col[j:j + 2], 16) / 255 for j in (1, 3, 5))
        # первый контур (красная «М» или цветной параллелограмм) — с тонкой белой кромкой, чтобы значок читался на любой основе
        out.append({"op": "path", "closed": True, "fill": c, "stroke": (1, 1, 1) if n == 0 else None, "width": 0.2 if n == 0 else 0,
                    "dash": None, "rings": rings, "evenodd": True, "name": "Значок станции"})
    return out
