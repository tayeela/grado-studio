for (code, slug, title, ppm, hexc, cmyk, angle, density, line, line_color,
     label, group) in ROWS:
    sid = f"lgr.{slug}"
    dash_px, dash_mm = DASH[line]
    prio = PRIORITY.get(code)
    w_mm = WIDTH_MM.get(code, 0.5)
    entry = {
        "title": title,
        "group": group,
        "lgr_code": code,
        "lgr_ppm_item": ppm,
        "lgr_priority": prio,
        "fill": None,
        "stroke": line_color,
        "width_mm": w_mm, "width_px": round(w_mm * 3.2, 2),
        "dash_mm": dash_mm, "dash_px": dash_px,
        "line_label": label,
        "label_field": None, "marker_mm": 1.2,
        # приоритет 1 (высший) → рисуется поверх: z = 100 + (28 - prio)
        "z": 100 + (28 - prio) if prio else 100,
        "codes": [],
        "dxf": {"name": f"LGR_{code}", "color": ACI.get(hexc, 7)},
    }
    if code in MARKERS:
        shape, period, size = MARKERS[code]
        entry["line_marker"] = {"shape": shape, "period_mm": period,
                                "size_mm": size,
                                "period_px": round(period * 2, 1),
                                "size_px": round(size * 2, 1),
                                "dir": "out" if code in OUTWARD else "in"}
    if code in DOUBLE_MM:
        entry["double_mm"] = DOUBLE_MM[code]
        entry["double_px"] = round(DOUBLE_MM[code] * 2, 1)
    if angle is not None:
        px, mm = SPACING[density]
        entry["hatch"] = {"angle": angle, "cross": density == "cross",
                         "spacing_px": px, "spacing_mm": mm,
                         "color": hexc, "cmyk": cmyk}
    else:
        entry["hatch"] = False  # ЛГР без зоны (линия застройки, зона ВПП)
    styles[sid] = entry

