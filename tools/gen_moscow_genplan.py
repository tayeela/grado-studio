def slug(name):
    """Имя → латинский слаг для style_id. id уходит в .grado, поэтому нужна
    стабильная детерминированная транслитерация, а не порядковый номер."""
    out = []
    for ch in name.lower():
        if ch in _TR:
            out.append(_TR[ch])
        elif ch.isalnum():
            out.append(ch)
        else:
            out.append("_")
    s = "".join(out)
    while "__" in s:
        s = s.replace("__", "_")
    return s.strip("_")[:48]


def entry(sid, zone_value, title, group, fill, outline, dots=None):
    e = {
        "title": title,
        "group": group,
        # имя зоны КАК В ДАННЫХ (value категории QML) — по нему идёт маршрутизация
        "gp_zone": zone_value,
        "fill": fill,
        "stroke": outline,
        "width_mm": OUTLINE_MM, "width_px": to_px(OUTLINE_MM),
        "dash_mm": None, "dash_px": None,
        "hatch": False,
        "line_label": None, "label_field": None, "marker_mm": 1.2,
        "z": 10,                   # зоны — подложка под ЛГР (z=100+) и чертёж
        "codes": [],
        "dxf": {"name": f"GP_{slug(title)[:24]}", "color": ACI.get(fill, 7)},
    }
    if dots:
        # точечный узор ПОВЕРХ заливки (PointPatternFill эталона)
        e["dots"] = {"shape": "circle", "color": dots,
                     "size_mm": DOT_SIZE_MM, "size_px": to_px(DOT_SIZE_MM),
                     "spacing_mm": DOT_SPACING_MM, "spacing_px": to_px(DOT_SPACING_MM)}
    return sid, e


